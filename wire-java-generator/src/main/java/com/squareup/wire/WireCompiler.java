  public void compile() throws IOException {
    WireRun wireRun = createRun();
    wireRun.execute(fs, log);
  }

  public WireRun createRun() throws IOException {
    List<Target> targets = new ArrayList<>();
    if (javaOut != null) {
      targets.add(new JavaTarget(
          Collections.singletonList("*"),
          Collections.emptyList(),
          javaExclusive,
          javaOut,
          emitAndroid,
          emitAndroidAnnotations,
          emitCompact,
          emitDeclaredOptions,
          emitAppliedOptions,
          false /* buildersOnly */));
    }
    if (customOut != null || schemaHandlerFactoryClass != null) {
      if (customOut == null || schemaHandlerFactoryClass == null) {
        throw new IllegalArgumentException(
            "Both custom_out and schema_handler_factory_class need to be set");
      }
      targets.add(new CustomTarget(
          Collections.singletonList("*"),
          Collections.emptyList(),
          true /* exclusive */,
          customOut,
          customOptions,
          CustomTarget.newSchemaHandler(schemaHandlerFactoryClass)));
    }

    List<Path> sources = new ArrayList<>();
    for (String protoPath : protoPaths) {
      sources.add(Path.get(protoPath));
    }

    List<Location> allDirectories = new ArrayList<>();
    for (Path source : sources) {
      allDirectories.add(Location.get(source.toString()));
    }
    List<Location> sourcePath;
    List<Location> protoPath;

    if (!sourceFileNames.isEmpty()) {
      sourcePath = new ArrayList<>();
      for (String sourceFileName : sourceFileNames) {
        sourcePath.add(locationOfProto(sources, sourceFileName));
      }
      protoPath = allDirectories;
    } else {
      sourcePath = allDirectories;
      protoPath = Collections.emptyList();
    }

    List<com.squareup.wire.schema.EventListener> eventListeners = new ArrayList<>();
    for (String eventListenerFactoryClass : eventListenerFactoryClasses) {
      eventListeners.add(
          EventListenersKt.newEventListenerFactory(eventListenerFactoryClass).create());
    }

    return new WireRun(
        sourcePath,
        protoPath,
        treeShakingRoots,
        treeShakingRubbish,
        Collections.emptyList() /* moves */,
        null /* sinceVersion */,
        null /* untilVersion */,
        null /* onlyVersion */,
        targets,
        modules,
        permitPackageCycles,
        loadExhaustively,
        false /* escapeKotlinKeywords */,
        eventListeners,
        rejectUnusedRootsOrPrunes,
        opaqueTypes);
  }

  /** Searches {@code sources} trying to resolve {@code proto}. Returns the location if found. */
  private Location locationOfProto(List<Path> sources, String proto) throws IOException {
    // We cache ZIP openings because they are expensive.
    Map<Path, FileSystem> sourceToZipFileSystem = new LinkedHashMap<>();
    for (Path source : sources) {
      if (isRegularFile(source)) {
        sourceToZipFileSystem.put(source, fs.openZip(source));
      }
    }

    Path directoryEntry = null;
    for (Path source : sources) {
      FileSystem zip = sourceToZipFileSystem.get(source);
      boolean exists = zip != null
          ? zip.exists(Path.get("/").div(proto))
          : fs.exists(source.div(proto));
      if (exists) {
        directoryEntry = source;
        break;
      }
    }

    if (directoryEntry == null) {
      if (CoreLoader.isWireRuntimeProto(proto)) {
        return Location.get(CoreLoader.WIRE_RUNTIME_JAR, proto);
      }
      throw new FileNotFoundException("Failed to locate " + proto + " in " + sources);
    }

    return Location.get(directoryEntry.toString(), proto);
  }

  private boolean isRegularFile(Path path) throws IOException {
    return fs.metadataOrNull(path) != null
        && Boolean.TRUE.equals(fs.metadataOrNull(path).isRegularFile);
  }

