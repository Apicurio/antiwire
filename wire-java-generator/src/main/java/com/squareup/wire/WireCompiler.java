/**
 * Command line interface to the Wire Java generator.
 *
 * <p>Usage
 *
 * <pre>{@code
 * java WireCompiler --proto_path=<path>
 *   [--java_out=<path>]
 *   [--custom_out=<path>]
 *   [--schema_handler_factory_class=<class_name>]
 *   [--files=<protos.include>]
 *   [--includes=<message_name>[,<message_name>...]]
 *   [--excludes=<message_name>[,<message_name>...]]
 *   [--android]
 *   [--android-annotations]
 *   [--compact]
 *   [--custom_option=<key>,<value>]
 *   [file [file...]]
 * }</pre>
 *
 * <p>{@code --java_out} should provide the folder where the files generated by the Java code
 * generator should be placed.
 *
 * <p>{@code --event_listener_factory_class} should be used if you want to add a {@link
 * com.squareup.wire.schema.EventListener}. The factory class itself should be included in your
 * classpath.
 *
 * <p>{@code --logger_factory_class} should be used if you want a custom {@link WireLogger} to be
 * called. The factory class itself should be included in your classpath.
 *
 * <p>{@code --schema_handler_factory_class} should be used if you want a custom {@link
 * com.squareup.wire.schema.SchemaHandler} to be called. The factory class itself should be
 * included in your classpath. If set, {@code custom_out} should also be provided and will passed
 * to the factory's handler as a location to where it will be able to write files.
 *
 * <p>If the {@code --includes} flag is present, its argument must be a comma-separated list of
 * fully-qualified message or enum names. The output will be limited to those messages and enums
 * that are (transitive) dependencies of the listed names. The {@code --excludes} flag excludes
 * types, and takes precedence over {@code --includes}.
 *
 * <p>The {@code --dry_run} flag causes the compiler to just emit the names of the source files
 * that would be generated to stdout.
 *
 * <p>The {@code --android} flag will cause all messages to implement the {@code Parcelable}
 * interface. This implies {@code --android-annotations} as well.
 *
 * <p>The {@code --android-annotations} flag will add the {@code Nullable} annotation to optional
 * fields.
 *
 * <p>The {@code --opaque_types} takes a list of qualified named Protobuf types separated by a
 * ','. All types in the list will be evaluated as being of type {@code bytes}. On code generation,
 * the fields of such types will be using the platform equivalent of {@code bytes}, like {@code
 * okio.ByteString} for the JVM. Note that scalar types cannot be opaqued. The opaque step will
 * happen before the tree shaking one.
 *
 * <p>The {@code --compact} flag will emit code that uses reflection for reading, writing, and
 * toString methods which are normally implemented with code generation.
 *
 * <p>The {@code --custom_option} flag will be passed onto the custom {@link
 * com.squareup.wire.schema.SchemaHandler} if set. The flag can be used as many times as needed and
 * all key/value pairs will be aggregated into a map.
 *
 * <p>Port note: the Kotlin and Swift code generators are excluded from this port (DEC-6), so the
 * {@code --kotlin_out}, {@code --swift_out}, and related flags are rejected instead of being
 * honored.
 */
