  public static void main(String[] args) {
    try {
      WireCompiler wireCompiler = forArgs(args);
      wireCompiler.compile();
    } catch (WireException | IOException e) {
      System.err.print("Fatal: ");
      e.printStackTrace(System.err);
      System.exit(1);
    }
  }

  public static WireCompiler forArgs(java.nio.file.FileSystem fileSystem, WireLogger logger,
      String... args) throws WireException {
    return forArgs(FileSystem.asOkioFileSystem(fileSystem), logger, args);
  }

  public static WireCompiler forArgs(String... args) throws WireException {
    return forArgs(FileSystem.SYSTEM, new ConsoleWireLogger(), args);
  }

  static WireCompiler forArgs(FileSystem fileSystem, WireLogger logger, String... args)
      throws WireException {
    List<String> sourceFileNames = new ArrayList<>();
    List<String> treeShakingRoots = new ArrayList<>();
    List<String> treeShakingRubbish = new ArrayList<>();
    List<String> protoPaths = new ArrayList<>();
    Map<String, WireRun.Module> modules = Collections.emptyMap();
    String javaOut = null;
    String customOut = null;
    List<String> eventListenerFactoryClasses = new ArrayList<>();
    String loggerFactoryClass = null;
    String schemaHandlerFactoryClass = null;
    boolean emitAndroid = false;
    boolean emitAndroidAnnotations = false;
    boolean emitCompact = false;
    boolean emitDeclaredOptions = true;
    boolean emitAppliedOptions = true;
    boolean permitPackageCycles = false;
    boolean loadExhaustively = false;
    boolean javaExclusive = true;
    boolean dryRun = false;
    Map<String, String> customOptions = new LinkedHashMap<>();
    boolean rejectUnusedRootsOrPrunes = true;
    List<String> opaqueTypes = new ArrayList<>();

    for (String arg : args) {
      if (arg.startsWith(PROTO_PATH_FLAG)) {
        protoPaths.add(arg.substring(PROTO_PATH_FLAG.length()));

      } else if (arg.startsWith(JAVA_OUT_FLAG)) {
        if (javaOut != null) throw new IllegalStateException("java_out already set");
        javaOut = arg.substring(JAVA_OUT_FLAG.length());

      } else if (arg.startsWith(CUSTOM_OUT_FLAG)) {
        customOut = arg.substring(CUSTOM_OUT_FLAG.length());

      } else if (arg.startsWith(LOGGER_FACTORY_CLASS_FLAG)) {
        loggerFactoryClass = arg.substring(LOGGER_FACTORY_CLASS_FLAG.length());

      } else if (arg.startsWith(EVENT_LISTENER_FACTORY_CLASS_FLAG)) {
        eventListenerFactoryClasses.add(
            arg.substring(EVENT_LISTENER_FACTORY_CLASS_FLAG.length()));

      } else if (arg.startsWith(SCHEMA_HANDLER_FACTORY_CLASS_FLAG)) {
        schemaHandlerFactoryClass = arg.substring(SCHEMA_HANDLER_FACTORY_CLASS_FLAG.length());

      } else if (arg.startsWith(CUSTOM_OPTION_FLAG)) {
        String[] keyValue = arg.substring(CUSTOM_OPTION_FLAG.length()).split(",", 2);
        customOptions.put(keyValue[0], keyValue[1]);

      } else if (arg.startsWith(OPAQUE_TYPES_FLAG)) {
        String[] types = arg.substring(OPAQUE_TYPES_FLAG.length()).split(",");
        for (String type : types) {
          if (!type.isEmpty()) opaqueTypes.add(type);
        }

      } else if (arg.startsWith(FILES_FLAG)) {
        Path files = Path.get(arg.substring(FILES_FLAG.length()));
        try (BufferedSource source = Okio.buffer(fileSystem.source(files))) {
          for (String line; (line = source.readUtf8Line()) != null; ) {
            sourceFileNames.add(line);
          }
        } catch (IOException ex) {
          // Upstream reports the missing-file case as WireException and lets other IO failures
          // escape; this port cannot throw checked IOException from forArgs, so both land here.
          throw new WireException("Error processing argument " + arg, ex);
        }

      } else if (arg.startsWith(INCLUDES_FLAG)) {
        Collections.addAll(treeShakingRoots,
            arg.substring(INCLUDES_FLAG.length()).split(","));

      } else if (arg.startsWith(EXCLUDES_FLAG)) {
        Collections.addAll(treeShakingRubbish,
            arg.substring(EXCLUDES_FLAG.length()).split(","));

      } else if (arg.startsWith(MANIFEST_FLAG)) {
        String yaml = readUtf8(fileSystem, Path.get(arg.substring(MANIFEST_FLAG.length())));
        modules = parseManifestModules(yaml);

      } else if (arg.equals(NO_JAVA_EXCLUSIVE)) {
        javaExclusive = false;

      } else if (arg.equals(ANDROID)) {
        emitAndroid = true;

      } else if (arg.equals(ANDROID_ANNOTATIONS)) {
        emitAndroidAnnotations = true;

      } else if (arg.equals(COMPACT)) {
        emitCompact = true;

      } else if (arg.equals(DRY_RUN)) {
        dryRun = true;

      } else if (arg.equals(SKIP_DECLARED_OPTIONS)) {
        emitDeclaredOptions = false;

      } else if (arg.equals(SKIP_APPLIED_OPTIONS)) {
        emitAppliedOptions = false;

      } else if (arg.equals(PERMIT_PACKAGE_CYCLES_OPTIONS)) {
        permitPackageCycles = true;

      } else if (arg.equals(LOAD_EXHAUSTIVELY)) {
        loadExhaustively = true;

      } else if (arg.equals(IGNORE_UNUSED_ROOTS_AND_PRUNES)) {
        rejectUnusedRootsOrPrunes = false;

      } else if (isKotlinOrSwiftFlag(arg)) {
        throw new IllegalArgumentException(
            "Argument '" + arg + "' targets the Kotlin or Swift code generators, which are not"
                + " included in this port (DEC-6).");

      } else if (arg.startsWith("--")) {
        throw new IllegalArgumentException("Unknown argument '" + arg + "'.");

      } else {
        sourceFileNames.add(arg);
      }
    }

    if (javaOut == null && customOut == null) {
      throw new WireException(
          "Nothing to do! Specify " + JAVA_OUT_FLAG + " or " + CUSTOM_OUT_FLAG);
    }

    if (treeShakingRoots.isEmpty()) {
      treeShakingRoots.add("*");
    }

    return new WireCompiler(
        dryRun ? new DryRunFileSystem(fileSystem) : fileSystem,
        loggerFactoryClass != null
            ? WireLoggersKt.newLoggerFactory(loggerFactoryClass).create()
            : logger,
        protoPaths,
        javaOut,
        customOut,
        schemaHandlerFactoryClass,
        sourceFileNames,
        treeShakingRoots,
        treeShakingRubbish,
        rejectUnusedRootsOrPrunes,
        modules,
        emitAndroid,
        emitAndroidAnnotations,
        emitCompact,
        emitDeclaredOptions,
        emitAppliedOptions,
        permitPackageCycles,
        loadExhaustively,
        javaExclusive,
        eventListenerFactoryClasses,
        customOptions,
        opaqueTypes);
  }

  /**
   * True for the flags upstream WireCompiler accepts for its Kotlin and Swift targets. This port
   * ships neither generator, so the flags are reported as unsupported rather than silently
   * ignored.
   */
  private static boolean isKotlinOrSwiftFlag(String arg) {
    return arg.startsWith("--kotlin_")
        || arg.startsWith("--swift_")
        || arg.equals("--no_kotlin_exclusive")
        || arg.equals("--no_swift_exclusive")
        || arg.equals("--java_interop")
        || arg.equals("--emit_proto_reader_32");
  }

  private static String readUtf8(FileSystem fileSystem, Path path) throws WireException {
    try (BufferedSource source = Okio.buffer(fileSystem.source(path))) {
      return source.readUtf8();
    } catch (IOException ex) {
      throw new WireException("Error processing " + path, ex);
    }
  }

  /**
   * Parses the module manifest YAML. Upstream uses kotlinx.serialization with kaml; both are
   * banned here, so this accepts the same documented shape: a top-level map of module names to
   * maps whose keys are {@code dependencies}, {@code roots}, and {@code prunes}, each holding a
   * list of strings, written either inline ({@code [a, b]}) or as block list items
   * ({@code "- a"} lines indented under the key).
   */
  /** Upstream's {@code internal} Manifest.kt parseManifestModules; package-private here. */
  static Map<String, WireRun.Module> parseManifestModules(String yaml) {
    Set<String> defaultRoots = Collections.singleton("*");
    Set<String> defaultPrunes = Collections.emptySet();

    Map<String, Map<String, List<String>>> modules = new LinkedHashMap<>();
    String currentModule = null;
    List<String> currentList = null;

    String[] lines = yaml.split("\n", -1);
    for (int i = 0; i < lines.length; i++) {
      String line = stripComment(lines[i]);
      if (line.trim().isEmpty()) continue;
      int indent = line.length() - line.replaceFirst("^\\s+", "").length();
      String trimmed = line.trim();

      if (indent == 0 && !trimmed.startsWith("- ")) {
        // Upstream's kaml accepts the inline empty-module form `name: {}` (asserted by the
        // adopted upstream ManifestParseTest and WireCompilerTest manifest cases).
        boolean inlineEmptyModule = trimmed.endsWith(": {}");
        if (!trimmed.endsWith(":") && !inlineEmptyModule) {
          throw manifestError(i, "expected 'module:' but was '" + trimmed + "'");
        }
        currentModule = inlineEmptyModule
            ? trimmed.substring(0, trimmed.length() - 4)
            : trimmed.substring(0, trimmed.length() - 1);
        if (currentModule.isEmpty()) throw manifestError(i, "empty module name");
        modules.put(currentModule, new LinkedHashMap<>());
        currentList = null;
      } else if (currentModule == null) {
        throw manifestError(i, "indented line outside any module");
      } else if (trimmed.startsWith("- ")) {
        if (currentList == null) throw manifestError(i, "list item outside any list");
        currentList.add(trimmed.substring(2).trim());
      } else {
        int colon = trimmed.indexOf(':');
        if (colon == -1) {
          throw manifestError(i, "expected 'key:' but was '" + trimmed + "'");
        }
        String key = trimmed.substring(0, colon).trim();
        String inlineValue = trimmed.substring(colon + 1).trim();
        if (!key.equals("dependencies") && !key.equals("roots") && !key.equals("prunes")) {
          // Upstream's kaml parser rejects unknown keys with "Unknown property 'x'"; the exact
          // fragment is asserted by the adopted upstream ManifestParseTest, so this port's
          // hand-rolled parser reproduces it (2026-10-02, TASK-16).
          throw manifestError(i, "Unknown property '" + key + "'");
        }
        List<String> list = new ArrayList<>();
        modules.get(currentModule).put(key, list);
        if (inlineValue.isEmpty()) {
          // Block list: the '- item' lines follow indented under this key.
          currentList = list;
        } else if (inlineValue.equals("{}")) {
          currentList = null; // An empty module.
        } else if (inlineValue.startsWith("[") && inlineValue.endsWith("]")) {
          String inner = inlineValue.substring(1, inlineValue.length() - 1).trim();
          if (!inner.isEmpty()) {
            for (String item : inner.split(",")) {
              list.add(item.trim());
            }
          }
          currentList = null;
        } else {
          throw manifestError(i, "unsupported value '" + inlineValue + "'");
        }
      }
    }

    Map<String, WireRun.Module> result = new LinkedHashMap<>();
    for (Map.Entry<String, Map<String, List<String>>> entry : modules.entrySet()) {
      Map<String, List<String>> fields = entry.getValue();
      Set<String> dependencies = new java.util.LinkedHashSet<>(
          fields.getOrDefault("dependencies", Collections.emptyList()));
      List<String> roots = fields.getOrDefault("roots",
          Collections.singletonList("*"));
      List<String> prunes = fields.getOrDefault("prunes", Collections.emptyList());
      Set<String> rootSet = new java.util.LinkedHashSet<>(roots);
      Set<String> pruneSet = new java.util.LinkedHashSet<>(prunes);
      PruningRules pruningRules = !rootSet.equals(defaultRoots) || !pruneSet.equals(defaultPrunes)
          ? new PruningRules.Builder().addRoot(rootSet).prune(pruneSet).build()
          : null;
      result.put(entry.getKey(), new WireRun.Module(dependencies, pruningRules));
    }
    return result;
  }

  private static String stripComment(String line) {
    int hash = line.indexOf('#');
    return hash == -1 ? line : line.substring(0, hash);
  }

  private static IllegalArgumentException manifestError(int lineNumber, String message) {
    return new IllegalArgumentException(
        "Invalid module manifest at line " + (lineNumber + 1) + ": " + message);
  }

