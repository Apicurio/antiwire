package com.squareup.wire;

import static com.squareup.wire.testing.TestFiles.readUtf8;
import static org.junit.jupiter.api.Assertions.assertArrayEquals;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.squareup.wire.internal.Reflection;
import com.squareup.wire.testing.GeneratedMessages;
import com.squareup.wire.testing.TestCompilers;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * Generated models for {@code google.protobuf.Empty} compile against the port runtime with
 * no Kotlin on the classpath (TASK-16.1, docs/api-surface.md): the generator maps Empty to
 * {@link ProtoAdapter.UnitValue} fields carried by {@link ProtoAdapter#WIRE_EMPTY}, the
 * generated-code half of the TASK-26 dynamic-model mapping. Upstream maps Empty to
 * {@code kotlin.Unit} referencing {@code ProtoAdapter.EMPTY}, which cannot compile against
 * this runtime with or without kotlin-stdlib (the port's {@code EMPTY} is Void-typed); the
 * delivery-audit replay of that failure is preserved by this test's shape. The model is
 * generated by the CLI, compiled with {@code javac --release 11}, and round-tripped through
 * both the generated adapter and the reflection machinery, including present-versus-absent
 * fields and duplicate singular occurrences.
 */
public class GeneratedEmptyCompileTest {
  /** The audit reproduction shape: audit/empty/empty.proto at 295ef5f. */
  private static final String PROTO = ""
      + "syntax = \"proto3\";\n"
      + "import \"google/protobuf/empty.proto\";\n"
      + "\n"
      + "package antitempty;\n"
      + "\n"
      + "message Rpc {\n"
      + "  string name = 1;\n"
      + "  google.protobuf.Empty done = 2;\n"
      + "  repeated google.protobuf.Empty rep_done = 3;\n"
      + "}\n";

  @TempDir Path tempDir;

  @Test public void generatedEmptyModelCompilesAndRoundTrips() throws Exception {
    Path protoRoot = tempDir.resolve("proto");
    Files.createDirectories(protoRoot.resolve("antitempty"));
    Files.write(protoRoot.resolve("antitempty/rpc.proto"),
        PROTO.getBytes(java.nio.charset.StandardCharsets.UTF_8));
    Path out = tempDir.resolve("java_out");
    WireCompiler.forArgs(
        okio.FileSystem.SYSTEM,
        WireLogger.NONE,
        "--proto_path=" + protoRoot,
        "--java_out=" + out,
        "antitempty/rpc.proto")
        .compile();

    Path sourceFile = out.resolve("antitempty/Rpc.java");
    assertTrue(Files.isRegularFile(sourceFile), "the CLI did not emit " + sourceFile);
    Class<?> messageClass = TestCompilers.compileRelease11(
        sourceFile, "antitempty.Rpc", Files.createDirectories(tempDir.resolve("classes")),
        getClass());

    String source = readUtf8(sourceFile);
    assertTrue(!source.contains("kotlin"), "generated source references kotlin:\n" + source);
    assertTrue(source.contains("ProtoAdapter.UnitValue"), source);
    assertTrue(source.contains("ProtoAdapter.WIRE_EMPTY."), source);
    assertTrue(source.contains("\"com.squareup.wire.ProtoAdapter#WIRE_EMPTY\""), source);
    roundTripThroughGeneratedAdapter(messageClass);
    roundTripThroughReflectionAdapter(messageClass);
    presentVersusAbsentAndDuplicateOccurrences(messageClass);
  }

  private void roundTripThroughGeneratedAdapter(Class<?> messageClass) throws Exception {
    ProtoAdapter<Object> adapter = GeneratedMessages.adapterOf(messageClass);
    Object message = newMessage(messageClass, true);

    byte[] encoded = adapter.encode(message);
    assertEquals(encoded.length, adapter.encodedSize(message));
    assertArrayEquals(expectedWireBytes(), encoded);

    Object decoded = adapter.decode(encoded);
    assertEquals("rpc", GeneratedMessages.field(messageClass, decoded, "name"));
    assertEquals(ProtoAdapter.UnitValue.INSTANCE, GeneratedMessages.field(messageClass, decoded, "done"));
    assertEquals(expectedRepeatedDone(), GeneratedMessages.field(messageClass, decoded, "rep_done"));
    assertEquals(message, decoded);
    assertArrayEquals(encoded, adapter.encode(decoded));
  }

  /**
   * The reflection machinery must resolve the generated {@code #WIRE_EMPTY} adapter string to
   * the Unit-typed adapter; the wire bytes are the field framing both adapters write.
   */
  private void roundTripThroughReflectionAdapter(Class<?> messageClass) throws Exception {
    ProtoAdapter<Object> adapter = reflectionAdapterOf(messageClass);
    Object decoded = adapter.decode(expectedWireBytes());
    assertEquals(ProtoAdapter.UnitValue.INSTANCE, GeneratedMessages.field(messageClass, decoded, "done"));
    assertArrayEquals(expectedWireBytes(), adapter.encode(decoded));
  }

  /** A present Empty field survives as the unit value; an absent one stays null. */
  private void presentVersusAbsentAndDuplicateOccurrences(Class<?> messageClass)
      throws Exception {
    ProtoAdapter<Object> adapter = GeneratedMessages.adapterOf(messageClass);

    Object absent = newMessage(messageClass, false);
    byte[] absentBytes = adapter.encode(absent);
    assertArrayEquals(new byte[] { 0x0a, 0x03, 'r', 'p', 'c' }, absentBytes);
    assertNull(GeneratedMessages.field(messageClass, adapter.decode(absentBytes), "done"));
    assertEquals(0, ((List<?>) GeneratedMessages.field(messageClass, adapter.decode(absentBytes), "rep_done"))
        .size());

    // Duplicate singular occurrences merge to one present field, like every message field.
    byte[] duplicated = new byte[] {
        0x0a, 0x03, 'r', 'p', 'c',
        0x12, 0x00,
        0x12, 0x00,
    };
    Object decoded = adapter.decode(duplicated);
    assertEquals(ProtoAdapter.UnitValue.INSTANCE, GeneratedMessages.field(messageClass, decoded, "done"));
    assertArrayEquals(new byte[] { 0x0a, 0x03, 'r', 'p', 'c', 0x12, 0x00 },
        adapter.encode(decoded));
  }

  @SuppressWarnings({"unchecked", "rawtypes"})
  private static ProtoAdapter<Object> reflectionAdapterOf(Class<?> messageClass) {
    return (ProtoAdapter<Object>) (ProtoAdapter<?>) Reflection
        .createRuntimeMessageAdapter((Class) messageClass, null, Syntax.PROTO_3);
  }

  /** A message with every field present, or only the identity-valued string when absent. */
  private Object newMessage(Class<?> messageClass, boolean present) throws Exception {
    Class<?> builderClass = Class.forName("antitempty.Rpc$Builder", true,
        messageClass.getClassLoader());
    Object builder = builderClass.getDeclaredConstructor().newInstance();
    GeneratedMessages.invoke(builder, "name", "rpc");
    if (present) {
      GeneratedMessages.invoke(builder, "done", ProtoAdapter.UnitValue.INSTANCE);
      GeneratedMessages.invoke(builder, "rep_done", expectedRepeatedDone());
    }
    return builderClass.getMethod("build").invoke(builder);
  }

  private static List<ProtoAdapter.UnitValue> expectedRepeatedDone() {
    return Arrays.asList(ProtoAdapter.UnitValue.INSTANCE, ProtoAdapter.UnitValue.INSTANCE);
  }

  /**
   * The bytes an upstream-typed twin of this model would encode: the string, a present Empty
   * (tag 2, length 0), and two repeated Empty entries (tag 3, length 0 each), in tag order.
   */
  private static byte[] expectedWireBytes() throws IOException {
    okio.Buffer buffer = new okio.Buffer();
    ProtoWriter writer = new ProtoWriter(buffer);
    writer.writeTag(1, FieldEncoding.LENGTH_DELIMITED);
    writer.writeVarint32(3);
    writer.writeString("rpc");
    writer.writeTag(2, FieldEncoding.LENGTH_DELIMITED);
    writer.writeVarint32(0);
    writer.writeTag(3, FieldEncoding.LENGTH_DELIMITED);
    writer.writeVarint32(0);
    writer.writeTag(3, FieldEncoding.LENGTH_DELIMITED);
    writer.writeVarint32(0);
    return buffer.readByteArray();
  }
}
